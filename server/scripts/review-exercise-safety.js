'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { classifyRequirements } = require('../src/db/classify-requirements');
const { classifyContraindications } = require('../src/db/classify-contraindications');

const SEED = path.join(__dirname, '..', 'src', 'db', 'seeds', 'exercises.json');
const out = process.argv[2]
  || path.join(__dirname, '..', '..', 'docs', 'exercise-safety-review.md');

const raw = JSON.parse(fs.readFileSync(SEED, 'utf8'));
const all = Array.isArray(raw) ? raw : (raw.exercises || Object.values(raw).find(Array.isArray));
const live = all.filter((x) => x.promote);

const lines = [
  '# Exercise safety classification — review',
  '',
  'Generated by `npm run review:safety`. Every row is a decision the classifier',
  'made. Reject a whole movement class by editing the pattern that produced it,',
  'or override a single row by inserting one with `is_manual = 1`.',
  '',
  `Live exercises: ${live.length}`,
  '',
];

const requirementRows = [];
const contraRows = [];
for (const x of live) {
  for (const need of classifyRequirements(x)) {
    requirementRows.push({ name: x.name, tag: x.equipment, need });
  }
  for (const row of classifyContraindications(x)) {
    contraRows.push({ name: x.name, mg: x.muscle_group, bp: x.body_part, ...row });
  }
}

lines.push(`## Equipment requirements (${requirementRows.length})`, '');
lines.push('| Exercise | Primary tag | Also needs |', '|---|---|---|');
requirementRows.sort((a, b) => a.need.localeCompare(b.need) || a.name.localeCompare(b.name));
for (const r of requirementRows) {
  lines.push(`| ${r.name} | ${r.tag} | **${r.need}** |`);
}

// Grouped by injury region, because that is the unit a reviewer judges: "does
// a wrist injury really rule all of this out?" is answerable; "is
// shoulder_press_dip right?" is not, without knowing who it affects.
const byRegion = {};
for (const r of contraRows) (byRegion[r.region] ||= []).push(r);

lines.push('', `## Contraindications (${contraRows.length})`, '');
lines.push('| Region | Exercises blocked |', '|---|---|');
const regions = Object.entries(byRegion).sort((a, b) => b[1].length - a[1].length);
for (const [region, rows] of regions) lines.push(`| ${region} | ${rows.length} |`);

for (const [region, rows] of regions) {
  lines.push('', `### ${region} — ${rows.length} exercises`, '');
  lines.push('| Exercise | Pattern | Muscle group | Body part |', '|---|---|---|---|');
  rows.sort((a, b) => a.name.localeCompare(b.name));
  for (const r of rows) {
    lines.push(`| ${r.name} | ${r.pattern} | ${r.mg} | ${r.bp || ''} |`);
  }
}

fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, `${lines.join('\n')}\n`);
console.log(
  `wrote ${out}: ${requirementRows.length} requirements, ${contraRows.length} contraindications`,
);
