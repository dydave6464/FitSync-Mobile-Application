'use strict';
require('dotenv').config();
const fs = require('node:fs');
const path = require('node:path');
const { load } = require('../src/config');
const { createPool } = require('../src/db/pool');
const { classifyCategory, RULES } = require('../src/db/classify-categories');

// Signals that are NOT trusted to demote (see classify-categories.js) but are
// worth a human's eye. This is the classifier's deliberate blind spot.
const BROAD = /\brotat(e|ing|ion)\b|\bbalanc(e|ing)\b|\bhang(ing)?\b|\bkick(ing)?\b|\bwalk(ing)?\b|\broll(ing|out)?\b|\btwist(ing)?\b|\bhold(ing)?\b|\bplank(ing)?\b/;

function ruleFor(name) {
  const n = String(name).toLowerCase().trim();
  const hit = RULES.find((r) => r.pattern.test(n));
  return hit ? String(hit.pattern) : '';
}

function buildReport(exercises) {
  const demoted = [];
  const flagged = [];
  for (const x of exercises) {
    const category = classifyCategory(x);
    if (category !== 'strength') demoted.push({ ...x, category });
    else if (BROAD.test(String(x.name).toLowerCase())) flagged.push(x);
  }

  const L = [];
  L.push('# Exercise category classification — review', '');
  L.push('Generated by `npm run review:categories`. Override a single row by');
  L.push('setting `is_manual = 1` on it; the seed never rewrites those.', '');
  L.push(`Live exercises: ${exercises.length}`, '');
  L.push(`## A. Demoted (${demoted.length})`, '');
  L.push('Rows the classifier moved off `strength`. These are decisions to audit.', '');
  L.push('| id | Exercise | Muscle group | Category | Rule |');
  L.push('|---|---|---|---|---|');
  for (const x of demoted) {
    L.push(`| ${x.exercise_id} | ${x.name} | ${x.muscle_group} | **${x.category}** | \`${ruleFor(x.name)}\` |`);
  }
  L.push('');
  L.push(`## B. Flagged, not demoted (${flagged.length})`, '');
  L.push('Rows matching a broad signal that no confident rule demoted — the');
  L.push('classifier\'s deliberate blind spot. Expected to be almost entirely');
  L.push('correct as strength; this is a confirmation pass, not a decision pass.', '');
  L.push('| id | Exercise | Muscle group |');
  L.push('|---|---|---|');
  for (const x of flagged) {
    L.push(`| ${x.exercise_id} | ${x.name} | ${x.muscle_group} |`);
  }
  return L.join('\n') + '\n';
}

async function main() {
  const config = load();
  const pool = createPool(config.db);
  try {
    const [rows] = await pool.query(
      "SELECT exercise_id, name, muscle_group FROM exercises WHERE status = 'live' ORDER BY name",
    );
    const out = path.join(__dirname, '..', '..', 'docs', 'exercise-category-review.md');
    fs.mkdirSync(path.dirname(out), { recursive: true });
    fs.writeFileSync(out, buildReport(rows));
    console.log(`wrote ${out}`);
  } finally {
    await pool.end();
  }
}

if (require.main === module) {
  main().catch((err) => { console.error(err); process.exit(1); });
}

module.exports = { buildReport, BROAD };
